def is_capability_question(text: str) -> bool:
    normalized = " ".join(
        "".join(char if char.isalnum() else " " for char in text.casefold()).split()
    )
    if len(normalized) > 80:
        return False
    return normalized in {
        "что ты умеешь",
        "что умеет бот",
        "что умеет этот бот",
        "что умеет агент",
        "что умеет этот агент",
        "какие возможности",
        "какие у тебя возможности",
        "какие возможности у бота",
        "какие возможности у агента",
        "расскажи что ты умеешь",
        "расскажи что может этот бот",
        "расскажи что может этот агент",
        "что может бот",
        "что может этот бот",
        "что может агент",
        "что может этот агент",
    }
